"""The dual lattice, and the distinguisher the dual attack runs on it.

The design document asks for both attack families because the estimator reports the **minimum over
both** as the claimed security level: testing one gives a one-sided picture, and the one-sided
picture can only ever be optimistic.

## The lattice

For the q-ary lattice ``Lambda = { A c + q z }`` in the sample space ``Z^m``, the dual is

    Lambda* = { y in Z^m : A^T y == 0 (mod q) }

a full-rank sublattice of ``Z^m`` of determinant ``q^n``. Its short vectors are what the dual attack
uses: for ``y`` in ``Lambda*``,

    <y, b> = <y, A s + e> = <A^T y, s> + <y, e> == <y, e> (mod q)

and since ``y`` is short and ``e`` is small, ``<y, e>`` is much smaller than ``q`` — so the inner
product is detectable rather than uniform. A genuinely uniform ``b`` gives a uniform inner product.
That contrast is the distinguisher.

## The basis, and why the two checks are independent

Using the pivot that the normal form already selects — ``n`` rows of ``A`` forming ``A1``,
invertible modulo ``q`` — every ``y`` splits into a pivot block and the rest, and

    A1^T y_pivot + A2^T y_rest == 0 (mod q)   =>   y_pivot == -(A2 A1^{-1})^T y_rest

so the lattice is generated by

* ``n`` rows ``q * e_i`` on the pivot coordinates, and
* ``m - n`` rows carrying a unit in one rest coordinate and ``-(A2 A1^{-1})^T`` on the pivots.

The determinant is ``q^n``, which is the check that the basis spans the right volume. The other
check — that every row annihilates the primal sample space modulo ``q`` — is the *definition*, and
needs no derivation.

**Both are required because they fail for different bugs.** A basis built from a wrong pivot still
satisfies the annihilation property on the rows it produces while spanning the wrong volume; a
basis with the right determinant can still have rows that are not in the dual at all. Neither check
alone would catch both, and a corrupted basis is exercised against each separately in the tests.
"""

from __future__ import annotations

import math
