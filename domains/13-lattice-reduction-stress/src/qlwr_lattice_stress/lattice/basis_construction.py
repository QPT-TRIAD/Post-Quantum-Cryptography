"""The q-ary lattice a normal-form instance defines, and the checks that it is the right one.

Section 3.3 of the design document names the hazard this module exists for: *a wrong lattice reduces
perfectly*. A transposed base, an off-by-one in a block, a stale ``qI`` term or a sign error all
produce a full-rank lattice of the right determinant, which BKZ then reduces happily, yielding a
root-Hermite factor that looks like every other root-Hermite factor. There is no downstream signal.

So the construction is not trusted on inspection. Two independent checks run on it — a *structural*
one (every row satisfies the modular relation) and a *volumetric* one (the determinant is exactly
``q**m``) — because they fail for different bugs, and a basis that passes both is one that the
remainder of the project can be built on.

**The construction, written out.** For ``b = A x + e (mod q)`` with ``A`` of shape ``m x n``, the
lattice is the set of vectors carrying both the samples and the secret::

    Lambda = { (A c + q z, c) : c in Z^n, z in Z^m }  subset of  Z^m x Z^n

generated by ``n`` rows ``(A^T, I_n)`` — one per secret coordinate, each producing a column of
``A`` — together with ``m`` rows ``(q I_m, 0)``. The determinant is ``q^m``.

The instance's own relation puts ``(b - e, x) = (A x + q z0, x)`` in the lattice, so the lattice
contains a vector whose first block is within ``|e|`` of the public ``b``. That is what makes the
secret findable, and it is what the planted-vector test verifies before any reduction runs.
"""

from __future__ import annotations

from typing import Any

import numpy as np

from ..problem.normal_form import NormalFormInstance
